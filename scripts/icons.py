"""Write the icon block of src/goksen-ing.css from the goksen.ing Icon set.

T3 Code draws Lucide SVGs inline, and a theme can't change markup. So each mapped
icon gets one data: SVG mask, and the svg element paints its own colour through it:
lines and solids at full alpha take the part's ink; the Dither sits in the same
mask at 42 %, which lands on Edge grey (#686763 vs #6b6a66) on Ink.

The block goes between the /* @icons:start */ and /* @icons:end */ markers.

    python3 -I scripts/icons.py --set ../goksen.ing/src/lib/icons/set.ts

--set   the generated set.ts of goksen.ing (`pnpm icons` writes it)
--map   icons/map.json: a Lucide name (or a raw attribute selector) -> an icon name
--own   icons/own.json: glyphs drawn here, on the same 24-unit grid and layers
"""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DITHER = "M0 .75h24M1.5 3.75h24M0 6.75h24M1.5 9.75h24M0 12.75h24M1.5 15.75h24M0 18.75h24M1.5 21.75h24"
ATTRS = {"transform": "transform", "fillRule": "fill-rule", "clipRule": "clip-rule"}
NUM = re.compile(r"-?\d*\.\d+|-?\d+")
START, END = "/* @icons:start */", "/* @icons:end */"


def parse_set(path):
    src = Path(path).read_text()
    start = src.index("export const ICONS = {") + len("export const ICONS = ")
    end = src.index("} satisfies Record<string, IconData>", start) + 1
    body = re.sub(r"([{,]\s*)([A-Za-z_][A-Za-z0-9_]*)\s*:", r'\1"\2":', src[start:end])
    return json.loads(re.sub(r",(\s*[\]}])", r"\1", body))


def trim(d):
    # One decimal on the 24-unit grid is under 0.04 px at 16 px.
    def f(m):
        t = f"{round(float(m.group()), 1):.1f}".rstrip("0").rstrip(".") or "0"
        return "." + t[2:] if t.startswith("0.") else ("-." + t[3:] if t.startswith("-0.") else t)
    return re.sub(r" (?=-)", "", NUM.sub(f, d))


def render(layers):
    """Mirror goksen.ing's src/lib/icons/draw.tsx, as one white mask."""
    defs, body, n, dither = [], [], 0, False
    for role, d, *rest in layers:
        a = rest[0] if rest else {}
        sh = f"d='{trim(d)}'" + "".join(f" {ATTRS[k]}='{a[k]}'" for k in ATTRS if a.get(k))
        n += 1
        if role == "l":
            dash = f" stroke-dasharray='{a['dash']}'" if a.get("dash") else ""
            cap = " stroke-linecap='square'" if a.get("cap") else ""
            body.append(f"<path {sh}{dash}{cap}/>")
        elif role == "s":
            body.append(f"<path {sh} fill='#fff' stroke='none'/>")
        else:  # a tint or a knockout cuts what was painted before it
            if body:
                defs.append(f"<mask id='m{n}'><path d='M-1-1h26v26H-1z' fill='#fff' stroke='none'/><path {sh} stroke='none'/></mask>")
                body = [f"<g mask='url(#m{n})'>{''.join(body)}</g>"]
            if role == "t":
                dither = True
                defs.append(f"<clipPath id='c{n}'><path {sh}/></clipPath>")
                body.append(f"<use href='#h' clip-path='url(#c{n})'/>")
    if dither:
        defs.insert(0, f"<path id='h' d='{DITHER}' stroke-dasharray='1.5 1.5' stroke-opacity='.42'/>")
    return ("<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 24 24' fill='none' stroke='#fff' stroke-width='1.5' stroke-linejoin='miter'>"
            + (f"<defs>{''.join(defs)}</defs>" if defs else "") + "".join(body) + "</svg>")


def uri(svg):
    # Inside a quoted CSS url() only %, # and the double quote need escaping.
    return 'url("data:image/svg+xml,' + svg.replace("%", "%25").replace("#", "%23").replace('"', "'") + '")'


def target(key):
    return key if key.startswith("[") else f".lucide-{key}"


def block(icons, mapping):
    by = {}
    for key, name in mapping.items():
        if name not in icons:
            raise SystemExit(f"{key}: {name} is not in the set or icons/own.json")
        by.setdefault(name, []).append(target(key))
    every = ",".join(target(k) for k in mapping)
    out = [
        "/* Icon set: Streamline Sharp Duo Free (CC BY 4.0) in goksen.ing's two inks, plus own glyphs. Generated by scripts/icons.py. */",
        f"svg:is({every}) {{ mask: var(--gk-i) center / 100% 100% no-repeat; background: currentColor; }}",
        f"svg:is({every}) > * {{ display: none; }}",
    ]
    out += [f"svg:is({','.join(sels)}) {{ --gk-i: {uri(render(icons[name]))}; }}" for name, sels in by.items()]
    return "\n".join(out)


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--set", required=True)
    p.add_argument("--map", default=ROOT / "icons/map.json")
    p.add_argument("--own", default=ROOT / "icons/own.json")
    p.add_argument("--css", default=ROOT / "src/goksen-ing.css")
    a = p.parse_args()
    icons = parse_set(a.set)
    icons.update(json.loads(Path(a.own).read_text()))
    mapping = json.loads(Path(a.map).read_text())
    css_path = Path(a.css)
    css = css_path.read_text()
    i, j = css.index(START) + len(START), css.index(END)
    new = block(icons, mapping)
    css_path.write_text(css[:i] + "\n" + new + "\n" + css[j:])
    print(f"{len(set(mapping.values()))} icons for {len(mapping)} targets, {len(new)} bytes")


if __name__ == "__main__":
    main()
